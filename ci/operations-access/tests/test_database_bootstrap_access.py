    def admitted(self,resource,obj,group='lifecycle-apply',operation='CREATE',env='dev',options=None):
        policy=self.policies(env)[resource]
        request={'namespace':obj['metadata']['namespace'],'operation':operation,'userInfo':{'groups':['cp:'+env+':'+group]},'options':options or {}}
        variables={'target':obj}
        if resource=='jobs':variables.update(pod=obj['spec']['template']['spec'],container=obj['spec']['template']['spec']['containers'][0])
        values={'request':wrap(request),'object':wrap(obj),'oldObject':wrap(obj),'variables':wrap(variables)}
        return all(evaluate(x['expression'],values) for x in policy['spec']['validations'])
    def test_exact_api_grants_dev_and_prod(self):
        for env in ('dev','prod'):
            items=access.rbac(dict(C,environment=env));ns='contract2whale-demo'
            for role in ('lifecycle-plan','lifecycle-apply'):
                group='cp:'+env+':'+role
                for api,resources in [('',('pods','configmaps','serviceaccounts')),('apps',('deployments','statefulsets')),('batch',('jobs','cronjobs'))]:
                    for resource in resources:
                        for verb in ('get','list'):self.assertTrue(allows(items,group,verb,api,resource,ns), (env,role,verb,resource))
                for resource in ('secrets','pods/log','pods/exec','serviceaccounts/token'):
                    for verb in ('get','list','create','patch','update','delete'):self.assertFalse(allows(items,group,verb,'',resource,ns))
                for api,resource in [('','configmaps'),('batch','jobs')]:
                    self.assertEqual(allows(items,group,'create',api,resource,ns),role=='lifecycle-apply')
                    for verb in ('patch','update','delete','deletecollection'):self.assertFalse(allows(items,group,verb,api,resource,ns))
                    for other in ('argocd','kube-system','monitoring'):self.assertFalse(allows(items,group,'create',api,resource,other))
            group='cp:'+env+':lifecycle-destroy'
            for api,resource in [('','configmaps'),('batch','jobs')]:
                self.assertTrue(allows(items,group,'delete',api,resource,ns))
                for verb in ('create','patch','update','deletecollection'):self.assertFalse(allows(items,group,verb,api,resource,ns))
                for other in ('argocd','kube-system','monitoring'):self.assertFalse(allows(items,group,'delete',api,resource,other))
    def test_existing_handler_shapes_are_admitted(self):
        for env in ('dev','prod'):
            for resource,obj in zip(('jobs','configmaps'),self.objects(env)):
                for group in ('lifecycle-apply','incident-apply'):self.assertTrue(self.admitted(resource,obj,group,env=env),(env,resource,group))
                for group in ('lifecycle-plan','lifecycle-destroy'):self.assertFalse(self.admitted(resource,obj,group,env=env))
                self.assertFalse(self.admitted(resource,obj,operation='UPDATE',env=env))
