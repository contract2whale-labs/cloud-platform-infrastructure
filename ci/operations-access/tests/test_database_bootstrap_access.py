class Value:
    def __init__(self, value): self._value=value
    def __getattr__(self, key):
        if isinstance(self._value,dict) and key in self._value:return wrap(self._value[key])
        raise AttributeError(key)
    def __getitem__(self, key):return wrap(self._value[key])
    def __iter__(self):return iter(self._value) if isinstance(self._value,dict) else iter(wrap(x) for x in self._value)
    def __eq__(self, other):return self._value==(other._value if isinstance(other,Value) else other)
    def size(self):return len(self._value)
    def matches(self, pattern):return re.search(pattern,self._value) is not None
    def startsWith(self, prefix):return self._value.startswith(prefix)
    def __add__(self, other):return self._value+other
    def __radd__(self, other):return other+self._value
    def __int__(self):return int(self._value)

def wrap(x):return Value(x) if isinstance(x,(dict,list,str)) else x

def evaluate(expression, values):
    expression=re.sub(r'has\(([^()]*)\)',lambda m:'present('+repr(m[1])+')',expression)
    expression=re.sub(r'([A-Za-z0-9_.]+)\.(all|exists)\(([a-z]+), ([^()]*)\)',lambda m:('all' if m[2]=='all' else 'any')+'('+m[4]+' for '+m[3]+' in '+m[1]+')',expression)
    parts=re.split(r'("(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\')',expression)
    for n in range(0,len(parts),2):
        parts[n]=re.sub(r'\bfalse\b','False',re.sub(r'\btrue\b','True',parts[n])).replace('&&',' and ').replace('||',' or ')
        parts[n]=re.sub(r'!(?!=)','not ',parts[n])
    translated=''.join(parts)
    scope={**values,'all':all,'any':any,'int':int,'__builtins__':{}}
    def present(path):
        try:eval(path,scope);return True
        except (KeyError,AttributeError,IndexError):return False
    scope['present']=present
    try:return bool(eval(translated,scope))
    except (KeyError,AttributeError,IndexError,TypeError,ValueError):return False

